/** 표에 없는 장비 카테고리에 둘 옵션. 장비에는 대개 이것들이 붙는다. */
const EQUIPMENT_FALLBACK = ['아이템 색상', '내구력', '세공 옵션', '인챈트', '특별 개조', '에르그', '세트 효과'];

/** 한 카테고리의 옵션 이름. 표에 없으면 장비는 흔한 장비 옵션을, 나머지는 빈 목록을 준다. */
function typesOfLeaf(category: string): readonly string[] {
  return OPTION_TYPES_BY_CATEGORY[category] ?? (isEquipmentCategory(category) ? EQUIPMENT_FALLBACK : []);
}

/** 고른 카테고리(묶음이면 그 아래 카테고리 모두, 전체면 모든 카테고리)에 붙는 옵션 이름. */
export function optionTypesFor(category: string): string[] {
  const leaves = leavesOfGroupKey(category) ?? (category ? [category] : AUCTION_ITEM_CATEGORIES);
  return [...new Set(leaves.flatMap(typesOfLeaf))];
}

/** 옵션 이름 가운데 하나라도 붙는 카테고리. 카테고리 없이 상세 검색 조건만으로 찾을 때 훑을 곳을 고른다. */
export function categoriesWithOptionTypes(types: readonly string[]): string[] {
  return AUCTION_ITEM_CATEGORIES.filter((category) => typesOfLeaf(category).some((type) => types.includes(type)));
}

